const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!);

function describeState(s: Scenario): string[] {
  const buddies = s.buddies.length
    ? s.buddies.map((b) => `${b.name} (${b.where === "near" ? "30 km" : b.where === "far" ? "155 km" : "no position"}, ${b.interests.join("+")})`).join(", ")
    : "none";
  return [
    `Email: ${s.verified ? "verified" : "not verified"}`,
    `Bio: ${s.bio}`,
    `Interests: ${s.interests.join(", ") || "none"}`,
    `Own location: ${s.hasLocation ? "Copenhagen" : "not set"}`,
    `Other users: ${buddies}`,
    `Hi5 sent: ${s.hi5Sent ? "yes" : "no"}`,
    `Already posted about: ${s.postedAbout.join(", ") || "nothing"}`,
  ];
}

