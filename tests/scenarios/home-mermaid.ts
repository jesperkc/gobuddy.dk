import { BLOCK_LABELS, type Blocks, type Scenario } from "./home-fixtures";

export interface Result {
  scenario: Scenario;
  /** What the page actually rendered. */
  seen: Blocks;
  mismatches: Array<keyof Blocks>;
}

/** End points of the decision tree. */
type Leaf = "U_BIO" | "U_FP" | "U_NONE" | "V_NONE" | "HOLD" | "V_BIO" | "V_FP" | "V_DONE";
const LEAVES: Leaf[] = ["U_BIO", "U_FP", "U_NONE", "V_NONE", "HOLD", "V_BIO", "V_FP", "V_DONE"];
const EMPTY_LEAVES: Leaf[] = ["U_NONE", "V_NONE", "V_DONE"];

/**
 * Place a scenario on an end point of the tree from what the page *rendered*
 * (not from what we expected), so a behavior change moves the scenario.
 */
export function leafFor({ scenario: s, seen }: Result): Leaf {
  if (!s.verified) return seen.bioPrompt ? "U_BIO" : seen.firstPostPrompt ? "U_FP" : "U_NONE";
  if (!seen.bestMatch && !seen.noNearby) return "V_NONE";
  if (seen.bioPrompt) return "V_BIO";
  if (seen.firstPostPrompt) return "V_FP";
  return seen.bestMatch && !s.hi5Sent ? "HOLD" : "V_DONE";
}

/** Node ids a scenario passes through, from the first question to its end point. */
export function pathFor(r: Result): string[] {
  const leaf = leafFor(r);
  const { seen } = r;
  if (!r.scenario.verified) {
    return leaf === "U_BIO" ? ["START", "V", "BANNER", "UBIO", leaf] : ["START", "V", "BANNER", "UBIO", "UFP", leaf];
  }
  if (leaf === "V_NONE") return ["START", "V", "INT", leaf];
  const head = ["START", "V", "INT", "TM", seen.bestMatch ? "BM" : "NN"];
  if (leaf === "HOLD") return [...head, "HI", leaf];
  const mid = seen.bestMatch ? [...head, "HI", "ASK", "VBIO"] : [...head, "ASK", "VBIO"];
  return leaf === "V_BIO" ? [...mid, leaf] : [...mid, "VFP", leaf];
}

const tag = (r: Result) => `#${r.scenario.id.slice(0, 2)}${r.scenario.surprising ? "⚠" : ""}${r.mismatches.length ? "✗" : ""}`;

/** The Mermaid flowchart source (no code fence). */
export function treeSource(results: Result[]): string {
  const byLeaf = new Map<Leaf, Result[]>();
  for (const r of results) byLeaf.set(leafFor(r), [...(byLeaf.get(leafFor(r)) ?? []), r]);
  const tags = (leaf: Leaf) => (byLeaf.get(leaf) ?? []).map(tag).join(" ") || "no scenario";
  const warn = (leaf: Leaf) => (byLeaf.get(leaf) ?? []).some((r) => r.scenario.surprising);
  const bad = (leaf: Leaf) => (byLeaf.get(leaf) ?? []).some((r) => r.mismatches.length);

  return `flowchart TD
  START(["/home loads"]) --> V{"Email verified?"}

  V -->|"no"| BANNER["Always: VerifyEmailBanner<br/>Feed shows LockedNote"]
  BANNER --> UBIO{"Bio pending?<br/>(empty and not skipped)"}
  UBIO -->|"yes"| U_BIO["BioPrompt<br/>${tags("U_BIO")}"]
  UBIO -->|"no"| UFP{"Interest left<br/>to post about?"}
  UFP -->|"yes"| U_FP["FirstPostPrompt<br/>saved as draft until verified<br/>${tags("U_FP")}"]
  UFP -->|"no"| U_NONE["No prompt<br/>${tags("U_NONE")}"]

  V -->|"yes"| INT{"Has interests?"}
  INT -->|"no"| V_NONE["No match block, no prompt<br/>only the checklist<br/>${tags("V_NONE")}"]
  INT -->|"yes"| TM{"Top match?<br/>shares an interest AND<br/>(within 50 km OR distance unknown)"}

  TM -->|"yes"| BM["BestMatchCard"]
  TM -->|"no"| NN["NoNearbyBuddies"]

  BM --> HI{"Hi5 sent?"}
  HI -->|"no"| HOLD["askVisible = false<br/>no bio or post prompt<br/>${tags("HOLD")}"]
  HI -->|"yes"| ASK
  NN --> ASK["askVisible = true"]

  ASK --> VBIO{"Bio pending?"}
  VBIO -->|"yes"| V_BIO["BioPrompt<br/>${tags("V_BIO")}"]
  VBIO -->|"no"| VFP{"Interest left<br/>to post about?"}
  VFP -->|"yes"| V_FP["FirstPostPrompt<br/>${tags("V_FP")}"]
  VFP -->|"no"| V_DONE["No prompt<br/>${tags("V_DONE")}"]

  classDef prompt fill:#dbeafe,stroke:#2e7cc5,color:#0b2a4a
  classDef empty fill:#f3f4f6,stroke:#9ca3af,color:#374151
  classDef warn fill:#fef3c7,stroke:#d97706,color:#78350f
  classDef bad fill:#fee2e2,stroke:#dc2626,color:#7f1d1d
  class BM,NN prompt
${LEAVES.map((l) => `  class ${l} ${bad(l) ? "bad" : warn(l) ? "warn" : EMPTY_LEAVES.includes(l) ? "empty" : "prompt"}`).join("\n")}`;
}

const STATE_SOURCE = `flowchart LR
  subgraph Inputs
    A["email_verifications row"] --> verified
    B["profile.bio, firstPosts.bioSkipped"] --> bioPending
    C["profile.user_interests"] --> hasInterests
    D["profiles + haversine ≤ 50 km"] --> topMatch
    E["hi5s sent by me"] --> hi5Sent
    F["my activity_posts, drafts, skips"] --> interestLeft
  end
  topMatch --> askVisible
  hi5Sent --> askVisible
  verified --> askVisible
  askVisible["askVisible =<br/>unverified OR<br/>(verified AND (hi5Sent OR no top match))"]`;

/** docs/scenarios/home-prompts.md: the same tree as Markdown, for GitHub / editors. */
export function renderMermaidDoc(results: Result[]): string {
  const flagged = results.filter((r) => r.scenario.surprising);
  const failing = results.filter((r) => r.mismatches.length);

  return `# /home prompts: decision tree

> Generated by \`tests/scenarios/home-prompts.spec.ts\`. Do not edit by hand: run
> \`npx playwright test tests/scenarios/home-prompts.spec.ts\` to refresh it.

Each end point lists the scenarios that landed there, placed by what the page rendered.
\`#06\` = scenario \`06-…\`, \`⚠\` = behavior worth a second look, \`✗\` = rendered something other than expected.
For the interactive version (pick a scenario, see its path and screenshot) open \`docs/scenarios/home-prompts/index.html\`.

\`\`\`mermaid
${treeSource(results)}
\`\`\`

${failing.length ? `## Differs from expectation\n\n${failing.map((r) => `- \`${r.scenario.id}\`: ${r.mismatches.join(", ")}`).join("\n")}\n\n` : ""}${flagged.length ? `## Worth a second look\n\n${flagged.map((r) => `- **${tag(r)}** ${r.scenario.title}: ${r.scenario.surprising}`).join("\n")}\n\n` : ""}## State that drives it

\`\`\`mermaid
${STATE_SOURCE}
\`\`\`
`;
}

